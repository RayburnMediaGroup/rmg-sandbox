// ─── Types ────────────────────────────────────────────────────────

interface MemberInput  { name: string; role: string; }
interface TrackInput   { number: number; title: string; duration: string; }

interface FormData {
  // Step 1 — Identity
  name: string;
  genre: string;
  tagline: string;
  origin: string;
  founded: string;
  // Step 2 — Story
  bio: string[];
  members: MemberInput[];
  awards: string;
  // Step 3 — Links
  spotify: string;
  appleMusic: string;
  youtube: string;
  soundcloud: string;
  bandcamp: string;
  instagram: string;
  tiktok: string;
  facebook: string;
  twitter: string;
  youtubeChannel: string;
  bookingEmail: string;
  newsletterUrl: string;
  // Step 4 — Release
  releaseTitle: string;
  releaseType: "album" | "ep" | "single" | "live";
  releaseDate: string;
  releaseDescription: string;
  tracks: TrackInput[];
}

