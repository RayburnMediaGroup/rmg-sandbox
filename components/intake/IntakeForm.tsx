function StepGenerate({ f, tokens }: { f: FormData; tokens: TokenSet }) {
  const [copied, setCopied] = useState(false);
  const output = buildDataTs(f);

  const copy = () => {
    navigator.clipboard.writeText(output).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  };

  const download = () => {
    const blob = new Blob([output], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "data.ts";
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div>
      <p style={{ fontFamily: "monospace", fontSize: "0.6rem", letterSpacing: "0.14em", color: tokens.muted2, textTransform: "uppercase", marginBottom: "1rem" }}>Generated data.ts</p>

      {/* Actions */}
      <div style={{ display: "flex", gap: "0.75rem", marginBottom: "1.25rem" }}>
        <button
          type="button"
          onClick={copy}
          style={{
            fontFamily: "monospace", fontSize: "0.62rem", letterSpacing: "0.14em",
            textTransform: "uppercase",
            background: tokens.accent, color: "#000",
            border: "none", borderRadius: "6px", padding: "10px 20px", cursor: "pointer",
            fontWeight: 600,
          }}
        >
          {copied ? "✓ Copied" : "Copy to Clipboard"}
        </button>
        <button
          type="button"
          onClick={download}
          style={{
            fontFamily: "monospace", fontSize: "0.62rem", letterSpacing: "0.14em",
            textTransform: "uppercase",
            background: "transparent", color: tokens.accent,
            border: `1px solid ${tokens.border2}`, borderRadius: "6px", padding: "10px 20px", cursor: "pointer",
          }}
        >
          Download data.ts
        </button>
      </div>

      {/* Code block */}
      <pre
        style={{
          background: tokens.bg3,
          border: `1px solid ${tokens.border}`,
          borderRadius: "8px",
          padding: "20px",
          overflowX: "auto",
          fontFamily: "'Space Mono', monospace",
          fontSize: "0.72rem",
          lineHeight: 1.65,
          color: tokens.text,
          whiteSpace: "pre",
          maxHeight: 480,
          overflowY: "auto",
        }}
      >
        {output}
      </pre>

      {/* Next steps */}
      <div style={{ marginTop: "2rem", padding: "1.25rem 1.5rem", background: tokens.bg2, border: `1px solid ${tokens.border}`, borderLeft: `3px solid ${tokens.accent}`, borderRadius: "8px" }}>
        <p style={{ fontFamily: "monospace", fontSize: "0.6rem", letterSpacing: "0.14em", textTransform: "uppercase", color: tokens.accent, marginBottom: "0.75rem" }}>Next Steps</p>
        <ol style={{ fontFamily: `'Inter', system-ui, sans-serif`, fontSize: "0.84rem", color: tokens.text, lineHeight: 1.8, paddingLeft: "1.25rem" }}>
          <li>Copy or download <code style={{ fontFamily: "monospace", fontSize: "0.78rem", color: tokens.accentWarm }}>data.ts</code></li>
          <li>Drop it into your BandStack project at <code style={{ fontFamily: "monospace", fontSize: "0.78rem", color: tokens.accentWarm }}>lib/data.ts</code></li>
          <li>Replace any <code style={{ fontFamily: "monospace", fontSize: "0.78rem", color: tokens.accentWarm }}>undefined</code> fields with real URLs</li>
          <li>Add cover art to <code style={{ fontFamily: "monospace", fontSize: "0.78rem", color: tokens.accentWarm }}>public/</code> and set <code style={{ fontFamily: "monospace", fontSize: "0.78rem", color: tokens.accentWarm }}>coverArt</code></li>
          <li>Run <code style={{ fontFamily: "monospace", fontSize: "0.78rem", color: tokens.accentWarm }}>npm run dev</code> — your site is live</li>
        </ol>
      </div>
    </div>
  );
}

// ─── Main form ────────────────────────────────────────────────────

export default function IntakeForm() {
  const [step, setStep] = useState(0);
  const [form, setForm] = useState<FormData>(EMPTY);

  const set = useCallback((k: keyof FormData, v: unknown) => {
    setForm((prev) => ({ ...prev, [k]: v }));
  }, []);

  const tokens = form.genre
    ? resolveTokens([form.genre])
    : { bg: "#0c0b09", bg2: "#141210", bg3: "#1d1a16", border: "rgba(255,220,150,0.06)", border2: "rgba(255,220,150,0.12)", accent: "#888", accentWarm: "#aaa", accentDim: "rgba(136,136,136,0.10)", text: "#ede8df", muted: "rgba(237,232,223,0.5)", muted2: "rgba(237,232,223,0.25)", displayFont: "Bebas Neue", bodyFont: "Inter", displayFontUrl: "", bodyFontUrl: "" } as TokenSet;

  const canProceed = () => {
    if (step === 0) return f.name.trim().length > 0 && f.genre.length > 0;
    return true;
  };
  const f = form;

  const stepContent = [
    <StepIdentity key="1" f={f} set={set} tokens={tokens} />,
    <StepStory    key="2" f={f} set={set} tokens={tokens} />,
    <StepLinks    key="3" f={f} set={set} tokens={tokens} />,
    <StepRelease  key="4" f={f} set={set} tokens={tokens} />,
    <StepGenerate key="5" f={f} tokens={tokens} />,
  ];

  return (
    <main style={{ minHeight: "100vh", background: tokens.bg, transition: "background 0.4s ease" }}>

      {/* Top bar */}
      <header style={{
        position: "fixed", top: 0, left: 0, right: 0, zIndex: 50,
        background: "rgba(12,11,9,0.85)",
        backdropFilter: "blur(16px)",
        WebkitBackdropFilter: "blur(16px)",
        borderBottom: `1px solid ${tokens.border}`,
        height: 56,
        display: "flex", alignItems: "center",
        padding: "0 32px",
        justifyContent: "space-between",
      }}>
        <span style={{ fontFamily: `'Bebas Neue', sans-serif`, fontSize: "1.1rem", letterSpacing: "0.06em", color: tokens.text }}>
          BandStack
        </span>
        {/* Progress pills */}
        <div style={{ display: "flex", gap: "0.4rem" }}>
          {STEPS.map((s, i) => (
            <button
              key={s}
              type="button"
              onClick={() => i < step + 1 && setStep(i)}
              style={{
                fontFamily: "monospace", fontSize: "0.52rem", letterSpacing: "0.14em",
                textTransform: "uppercase",
                padding: "4px 10px", borderRadius: "9999px",
                border: "1px solid",
                cursor: i <= step ? "pointer" : "default",
                borderColor: i === step ? tokens.accent : i < step ? tokens.border2 : tokens.border,
                background: i === step ? tokens.accentDim : "transparent",
                color: i === step ? tokens.accent : i < step ? tokens.muted : tokens.muted2,
                transition: "all 0.2s ease",
              }}
            >
              {s}
            </button>
          ))}
        </div>
      </header>

      {/* Content */}
      <div style={{ maxWidth: 620, margin: "0 auto", padding: "96px 28px 80px" }}>

        {/* Step heading */}
        <div style={{ marginBottom: "2.5rem" }}>
          <p style={{
            fontFamily: "monospace", fontSize: "0.58rem", letterSpacing: "0.2em",
            textTransform: "uppercase", color: tokens.accent, marginBottom: "0.4rem",
          }}>
            Step {step + 1} of {STEPS.length}
          </p>
          <h1 style={{
            fontFamily: `'Bebas Neue', var(--display-font, sans-serif)`,
            fontSize: "clamp(2rem, 5vw, 3.5rem)",
            lineHeight: 1, color: tokens.text,
            letterSpacing: "0.02em",
          }}>
            {["Who Are You?", "Tell Your Story", "Your Links", "Your Music", "You're Done."][step]}
          </h1>
          {step === 0 && f.genre && (
            <div style={{
              display: "inline-flex", alignItems: "center", gap: "8px",
              marginTop: "0.75rem", padding: "5px 14px",
              background: tokens.accentDim,
              border: `1px solid ${tokens.border2}`,
              borderRadius: "9999px",
            }}>
              <span style={{ width: 10, height: 10, borderRadius: "50%", background: tokens.accent, display: "inline-block" }} />
              <span style={{ fontFamily: "monospace", fontSize: "0.58rem", letterSpacing: "0.12em", color: tokens.accent }}>
                {f.genre} · {tokens.displayFont}
              </span>
            </div>
          )}
        </div>

        {/* Active step */}
        {stepContent[step]}

        {/* Navigation */}
        <div style={{
          display: "flex", justifyContent: "space-between",
          marginTop: "2.5rem", paddingTop: "1.5rem",
          borderTop: `1px solid ${tokens.border}`,
        }}>
          <button
            type="button"
            onClick={() => setStep((s) => Math.max(0, s - 1))}
            disabled={step === 0}
            style={{
              fontFamily: "monospace", fontSize: "0.62rem", letterSpacing: "0.14em",
              textTransform: "uppercase",
              background: "transparent", color: step === 0 ? tokens.muted2 : tokens.muted,
              border: `1px solid ${step === 0 ? tokens.border : tokens.border2}`,
              borderRadius: "6px", padding: "10px 22px",
              cursor: step === 0 ? "default" : "pointer",
            }}
          >
            ← Back
          </button>

          {step < STEPS.length - 1 && (
            <button
              type="button"
              onClick={() => setStep((s) => Math.min(STEPS.length - 1, s + 1))}
              disabled={!canProceed()}
              style={{
                fontFamily: "monospace", fontSize: "0.62rem", letterSpacing: "0.14em",
                textTransform: "uppercase",
                background: canProceed() ? tokens.accent : tokens.bg3,
                color: canProceed() ? "#000" : tokens.muted2,
                border: "none", borderRadius: "6px", padding: "10px 22px",
                cursor: canProceed() ? "pointer" : "default",
                fontWeight: 600,
                transition: "background 0.2s ease",
              }}
            >
              {step === STEPS.length - 2 ? "Generate →" : "Next →"}
            </button>
          )}
        </div>
      </div>

    </main>
  );
}
